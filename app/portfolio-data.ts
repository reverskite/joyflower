export type PortfolioPhoto = {
  image: string;
  alt: string;
  width: number;
  height: number;
  caption: string;
};

export type PortfolioItem = {
  slug: string;
  category: 'christmas' | 'planterior' | 'landscape';
  categoryLabel: string;
  name: string;
  title: string;
  // Lower numbers appear first in cards and the public directory. Omit to keep
  // unpinned cases in their original order; equal priorities also keep that order.
  displayPriority?: number;
  image: string;
  width?: number;
  height?: number;
  alt: string;
  description: string;
  space: string;
  lighting?: string;
  decorations: string;
  gallery?: PortfolioPhoto[];
  // Add only confirmed information; existing entries need no new fields.
  region?: string;
  detailDescription?: string[];
  seoTitle?: string;
  seoDescription?: string;
  // Preserve the existing captioned detail page without a second case definition.
  detail?: {
    eyebrow: string;
    lead: string[];
    alt: string;
    caption: string;
    space: string;
    decorations: string;
    consultationNote: string;
    inquiryLabel: string;
  };
};

export const portfolioCategories = [
  ['christmas', '트리 대여'],
  ['planterior', '조화 플랜테리어'],
  ['landscape', '조경관리'],
] as const;

export function sortPortfolioItems(items: readonly PortfolioItem[] = portfolioItems) {
  return [...items].sort((a, b) =>
    (a.displayPriority ?? Number.MAX_SAFE_INTEGER) - (b.displayPriority ?? Number.MAX_SAFE_INTEGER));
}

export function relatedPortfolioItems(item: PortfolioItem) {
  return portfolioItems.filter(candidate => candidate.slug !== item.slug && candidate.category === item.category).slice(0, 3);
}

export function portfolioSeo(item: PortfolioItem) {
  return {
    title: item.seoTitle ?? `${item.name} | 조이플라워 포트폴리오`,
    description: item.seoDescription ?? item.description,
    image: item.image,
    imageAlt: item.detail?.alt ?? item.alt,
  };
}

